    required this.productId,
    required this.variantLabel,
    required this.lightLabel,
    required this.heavyLabel,
    required this.lightHeavyReason,
    required this.lightItems,
    required this.heavyItems,
  });

  bool get hasLightHeavy => heavyItems.isNotEmpty;
}

