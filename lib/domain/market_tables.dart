/// Standard Iranian steel market weight tables (light/heavy, Russian/European,
/// standard sheet sizes, column base plates, mesh, and shear studs).
class MarketPresetItem {
  final String id;
  final String label;
  final double? kgPerMetre;
  final double? kgPerPiece;
  final double? defaultPieceLengthM;
  final double? areaPerPieceM2;
  final String? variantNote;

  const MarketPresetItem({
    required this.id,
    required this.label,
    this.kgPerMetre,
    this.kgPerPiece,
    this.defaultPieceLengthM,
    this.areaPerPieceM2,
    this.variantNote,
  });
}

